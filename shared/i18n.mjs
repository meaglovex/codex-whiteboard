export const supportedLocales=['zh-CN','zh-TW','en'];
export function resolveLocale(preferences){
  const values=Array.isArray(preferences)?preferences:[preferences];
  for(const value of values){
    const tag=String(value||'').replaceAll('_','-').toLowerCase();
    if(/^zh(?:-|$)/.test(tag))return /(?:^|-)(?:hant|tw|hk|mo)(?:-|$)/.test(tag)?'zh-TW':'zh-CN';
    if(/^en(?:-|$)/.test(tag))return 'en';
  }
  return 'en';
}
export function translate(locale,key,params={}){
  const index=supportedLocales.indexOf(resolveLocale(locale));
  const template=(messages[key]||messages.operationFailed)[index];
  return template.replace(/\{(\w+)\}/g,(match,name)=>Object.hasOwn(params,name)?String(params[name]):match);
}
export function formatDateTime(locale,value,options={}){
  const date=new Date(value);if(Number.isNaN(date.valueOf()))return String(value);
  try{return new Intl.DateTimeFormat(locale,options).format(date);}catch{return new Intl.DateTimeFormat(resolveLocale(locale),options).format(date);}
}
const errorKeys=new Map(Object.entries(messages).filter(([key])=>key.startsWith('error.')).map(([key,row])=>[row[0],key]));
export function translateError(locale,message){
  if(/Failed to fetch|fetch failed|NetworkError|Load failed/i.test(message))return translate(locale,'error.network');
  if(/timeout|timed out|aborted/i.test(message))return translate(locale,'error.timeout');
  return errorKeys.has(message)?translate(locale,errorKeys.get(message)):message;
}
